/** Durable file handoff: claim a settled pathname, then deliver an immutable snapshot. */
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { randomUUID } from 'node:crypto'
import { z } from 'zod'

const fileName = z.string().refine(name => basename(name) === name && !/[\\/]/.test(name) && name.toLowerCase().endsWith('.md'))
const Manifest = z.object({ name: fileName, archive: fileName.optional(), mtimeMs: z.number().finite().optional() }).strict()
  .refine(value => !value.archive || value.mtimeMs !== undefined, 'An inbox snapshot requires its original timestamp')
/** One claimed input. The directory is generated by this process, not supplied by a manifest. */
export interface InboxClaim { directory: string }
const manifestPath = (claim: InboxClaim) => join(claim.directory, 'manifest.json')
const payloadPath = (claim: InboxClaim) => join(claim.directory, 'input.md')
const save = (claim: InboxClaim, value: z.infer<typeof Manifest>) => {
  const temp = manifestPath(claim) + '.tmp'
  writeFileSync(temp, JSON.stringify(value)); renameSync(temp, manifestPath(claim))
}

/** Recover previous claims and atomically move newly settled inputs out of the producer namespace. */
export function claimInboxFiles(root: string, stabilityMs: number): InboxClaim[] {
  mkdirSync(root, { recursive: true })
  const pending = join(root, '.pending'); mkdirSync(pending, { recursive: true })
  const claims = readdirSync(pending, { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => ({ directory: join(pending, entry.name) }))
  for (const entry of readdirSync(root, { withFileTypes: true }).filter(entry => entry.isFile() && entry.name.toLowerCase().endsWith('.md')).sort((a, b) => a.name.localeCompare(b.name))) {
    const source = join(root, entry.name)
    if (Date.now() - statSync(source).mtimeMs < stabilityMs) continue
    const claim = { directory: mkdtempSync(join(pending, 'claim-')), name: entry.name }
    save(claim, { name: entry.name })
    try { renameSync(source, payloadPath(claim)); claims.push(claim) }
    catch (error) { unlinkSync(manifestPath(claim)); rmdirSync(claim.directory); throw error }
  }
  return claims
}

/** Create the exact version named by a Trigger before its asynchronous admission starts. */
export function inboxSnapshot(root: string, claim: InboxClaim, stabilityMs: number): { path: string; relPath: string; content: string; mtimeMs: number } | undefined {
  const value = Manifest.parse(JSON.parse(readFileSync(manifestPath(claim), 'utf8')))
  const archive = join(root, 'done'); mkdirSync(archive, { recursive: true })
  if (!value.archive) {
    if (!existsSync(payloadPath(claim))) { unlinkSync(manifestPath(claim)); rmdirSync(claim.directory); return }
    const before = lstatSync(payloadPath(claim))
    if (!before.isFile() || Date.now() - before.mtimeMs < stabilityMs) return
    const content = readFileSync(payloadPath(claim), 'utf8'), after = statSync(payloadPath(claim))
    if (before.ino !== after.ino || before.size !== after.size || before.mtimeMs !== after.mtimeMs) return
    let name = value.name
    for (;;) {
      try { writeFileSync(join(archive, name), content, { flag: 'wx' }); break }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error; name = `${value.name.slice(0, -3)}-${randomUUID()}.md` }
    }
    value.archive = name; value.mtimeMs = before.mtimeMs; save(claim, value)
  }
  const target = join(archive, value.archive)
  if (!lstatSync(target).isFile()) throw new Error('Inbox snapshot is not a regular file')
  return { path: target, relPath: value.name, content: readFileSync(target, 'utf8'), mtimeMs: value.mtimeMs! }
}

/** Acknowledge only the claimed version; a newer input at the original pathname is never touched. */
export function finishInboxClaim(claim: InboxClaim, content: string): void {
  if (readFileSync(payloadPath(claim), 'utf8') !== content) {
    // An already-open writer changed the claimed inode. Retain it for a later
    // round; the delivered snapshot remains immutable and readable.
    const value = Manifest.parse(JSON.parse(readFileSync(manifestPath(claim), 'utf8')))
    save(claim, { name: value.name }); return
  }
  unlinkSync(payloadPath(claim)); unlinkSync(manifestPath(claim)); rmdirSync(claim.directory)
}
